"""Dataset inventory of the paper (25 development, 11 preliminary, 126 confirmatory datasets).

    python tools/list_datasets.py            writes DATASETS.md and edge_hac/data/DATA_SHA256SUMS.txt

N, F and K are counted on the shipped files (rows with missing values removed for the development data, as the loader
does; non-numeric columns already dropped for the OpenML data). The MANIFEST.json files in edge_hac/data/*/ record
the source, version and download date of every file.
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "edge_hac"), str(ROOT)]
from edgehac import datasets as D  # noqa: E402


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


rows, sums = [], []
edge = json.loads((ROOT / "edge_hac/data/edge/MANIFEST.json").read_text())
for n in D.ALL:
    d = D.load(n)
    if n in D.UCI18:
        p, src = ROOT / "data" / f"{n}.csv", "UCI ML Repository"
    else:
        p = ROOT / "edge_hac/data/edge" / f"{n}.npz"
        src = edge[n]["source"].replace("https://archive.ics.uci.edu/static/public/", "UCI id ").split("/")[0]
        src = src.replace("%3A", ":") if src.startswith("UCI") else edge[n]["source"]
    rows.append((n, "development", d["X"].shape[0], d["X"].shape[1], len(np.unique(d["y"])), src, p))
man = json.loads((ROOT / "edge_hac/data/validation/MANIFEST.json").read_text())
for n, m in man.items():
    p = ROOT / f"edge_hac/data/validation/{n}.npz"
    if "dropped" not in m and p.exists():
        rows.append((n, "preliminary", m["N"], m["F"], m["K"], f"OpenML id {m['id']} ({m['openml_name']} v{m['version']})", p))
man = json.loads((ROOT / "edge_hac/data/validation2/MANIFEST.json").read_text())["datasets"]
for n, m in sorted(man.items(), key=lambda kv: kv[1].get("id", 0)):
    p = ROOT / f"edge_hac/data/validation2/{n}.npz"
    if "dropped" in m or not p.exists():
        rows.append((n, "confirmatory (not downloaded)", "", "", "", f"OpenML id {m.get('id', n.split('_')[0])}", None))
        continue
    rows.append((n, "confirmatory", m["N"], m["F"], m["K"], f"OpenML id {m['id']} ({m['openml_name']} v{m['version']})", p))

out = ["# Datasets", "",
       "Generated by `python tools/list_datasets.py`. N, F and K are counted on the shipped files; F counts numeric features",
       "(non-numeric columns are dropped at download). K is the number of classes. Full SHA-256 sums are in",
       "`edge_hac/data/DATA_SHA256SUMS.txt`; the `MANIFEST.json` files in `edge_hac/data/*/` record source, version and",
       "download date. All datasets are public (UCI Machine Learning Repository, OpenML).", "",
       "| Dataset | Group | N | F | K | Source | File | SHA-256 (first 12) |", "|---|---|---:|---:|---:|---|---|---|"]
for n, g, N, F, K, src, p in rows:
    if p is None:
        out.append(f"| {n} | {g} | | | | {src} | -- | -- |")
        continue
    h = sha(p)
    sums.append(f"{h}  {p.relative_to(ROOT)}")
    out.append(f"| {n} | {g} | {N} | {F} | {K} | {src} | `{p.relative_to(ROOT)}` | `{h[:12]}` |")
(ROOT / "DATASETS.md").write_text("\n".join(out) + "\n")
(ROOT / "edge_hac/data/DATA_SHA256SUMS.txt").write_text("\n".join(sums) + "\n")
print(f"{len(rows)} rows; wrote DATASETS.md and edge_hac/data/DATA_SHA256SUMS.txt")
